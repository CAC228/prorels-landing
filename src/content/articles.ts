export function getPublishedArticles(source: Article[] = articles) {
  return source.filter(article => article.status === 'published');
}

export function getArticle(slug: string) {
  return getPublishedArticles().find(article => article.slug === slug);
}

export function readingMinutes(article: Article) {
  const text = [article.title, article.intro, article.takeaway, ...article.sections.flatMap(section => [
    section.title, ...section.paragraphs, ...(section.list ?? []), section.note ?? '',
    section.template ?? '', ...(section.table?.headers ?? []), ...(section.table?.rows.flat() ?? []),
  ])].join(' ');
  return Math.max(1, Math.ceil(text.trim().split(/\s+/u).length / 180));
}

export function formatArticleDate(date: string) {
  return new Intl.DateTimeFormat('ru-RU', { day: 'numeric', month: 'long', year: 'numeric', timeZone: 'Europe/Moscow' }).format(new Date(`${date}T12:00:00+03:00`));
}
